"""Executive report generation (Markdown, HTML, PDF) from executed pipeline results only. No fabricated values."""
from __future__ import annotations

import html
from datetime import datetime, timezone
from pathlib import Path

from ..core.config import settings
from ..data.schema import ARM_LABELS, TREATMENTS
from ..simulation.scenarios import SCENARIO_CATALOGUE, run_scenario

DISCLAIMER = ("This report is decision-support output generated by CAUSAL-X. It is not an official audit, regulatory certification, "
              "legal opinion, or determination of customer suitability or eligibility.")


def f(x, nd=3):
    return "n/a" if x is None else (f"{x:,.{nd}f}" if isinstance(x, float) else f"{x:,}")


def build_blocks(a, run: dict, scenario_results: list[dict]) -> list[tuple]:
    B = []
    cfg, summ = run["config"], run["summary"]
    strat = {s["key"]: s for s in run["strategies"] if "key" in s}
    rf, opt = strat.get("highest_risk_first_intensive"), strat.get("optimised", summ)
    B += [("title", "CAUSAL-X Executive Report"), ("p", f"Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} | Dataset: {a.dataset} | "
                                                      f"Model version: {a.model_version} | Policy version: {run['policy_version']}"), ("note", DISCLAIMER)]
    B.append(("h1", "1. Executive summary"))
    lines = [f"Optimised policy selects {summ['n_selected']:,} customers, spends {f(summ['budget_used'], 0)} of a {f(cfg['budget'], 0)} budget and has an "
             f"estimated net benefit of {f(summ['net_benefit'], 0)} ({f(summ['expected_avoided_events'], 1)} expected avoided adverse events, "
             f"+/- {f(summ['events_se_independent'], 1)} SE assuming independent estimate errors)."]
    if rf:
        lines.append(f"The highest-risk-first heuristic spends the same budget for an estimated net benefit of {f(rf['net_benefit'], 0)}; "
                     f"the optimiser's estimated advantage is {f(summ['net_benefit'] - rf['net_benefit'], 0)}.")
    if "synthetic_truth" in summ and rf and "synthetic_truth" in rf:
        lines.append(f"Synthetic benchmark (ground truth known only because data are synthetic): optimised {f(summ['synthetic_truth']['net_benefit'], 0)} vs "
                     f"highest-risk-first {f(rf['synthetic_truth']['net_benefit'], 0)}.")
    B.append(("bullets", lines))
    B.append(("h1", "2. Dataset description"))
    B.append(("bullets", [f"Source: {'synthetic (generated, not real customers)' if a.has_truth else 'uploaded'}; scenario: {a.scenario}; fingerprint {a.fingerprint[:16]}...",
                          f"Customers: {len(a.frame):,}; decision cohorts: {run['decision_cohorts']}; chronological split train 0-7, validation 8-9, test 10-11.",
                          "Synthetic data test methodology; they are not evidence of real-world intervention effectiveness."]))
    B.append(("h1", "3. Analytical objective"))
    B.append(("p", "Identify which customers should receive which intervention to reduce avoidable 30-day delinquency, subject to budget and capacity, by estimating "
                   "intervention-specific effects (not just predicting risk) and optimising allocation."))
    B.append(("h1", "4. Causal assumptions"))
    B.append(("bullets", ["Estimand: intention-to-treat effect of assignment; tau = E[Y(treat) - Y(none)], ARR = -tau.",
                          "Consistency/SUTVA, conditional exchangeability given pre-treatment covariates, positivity within eligible population, correct time zero.",
                          "In observational data exchangeability is untestable; sensitivity checks and E-values bound but do not remove this risk."]))
    rb = a.risk_bundle
    B.append(("h1", "5. Predictive results (risk layer)"))
    t = rb.metrics["test"]
    B.append(("p", f"Selected model: {rb.model_name} (lowest validation Brier). Held-out test cohorts 10-11: ROC-AUC {f(t['roc_auc'])}, PR-AUC {f(t['pr_auc'])}, Brier {f(t['brier'])}, "
                   f"event rate {f(t['event_rate'])}. Predictions describe risk under historical practice; they are not intervention effects."))
    B.append(("table", [["Model", "Val Brier", "Test ROC-AUC", "Test PR-AUC", "Test Brier"]] +
              [[c["model"], f(c["validation"]["brier"], 4), f(c["test"]["roc_auc"]), f(c["test"]["pr_auc"]), f(c["test"]["brier"], 4)] for c in rb.comparison]))
    B.append(("h1", "6. Causal estimation results"))
    rows = [["Intervention", "Unadjusted diff", "Reg. adjust.", "IPW", "AIPW [95% CI]", "Synthetic truth"]]
    for arm in TREATMENTS:
        s = a.causal_summary[arm]
        ai = s["aipw"]
        rows.append([ARM_LABELS[arm], f(s["difference_in_means"]["ate"]), f(s["regression_adjustment"]["ate"]), f(s["ipw"]["ate"]),
                     f"{f(ai['ate'])} [{f(ai['ci_low'])}, {f(ai['ci_high'])}]", f(s.get("synthetic_truth_ate")) if a.has_truth else "n/a"])
    B.append(("table", rows))
    B.append(("p", "Negative values mean fewer adverse outcomes. An unadjusted difference is an association; adjusted estimates require the assumptions above."))
    B.append(("h1", "7. Uplift evaluation"))
    rows = [["Intervention", "Qini: DR-learner", "Qini: T-learner", "Qini: risk-only ranking"]]
    for arm in TREATMENTS:
        e = a.uplift_eval.get(arm, {})
        if e.get("status") == "ok":
            r = e["rankers"]
            rows.append([ARM_LABELS[arm], f(r["dr_learner"]["qini"], 4), f(r["t_learner"]["qini"], 4), f(r["baseline_risk_only"]["qini"], 4)])
        else:
            rows.append([ARM_LABELS[arm], "insufficient evidence", "-", "-"])
    B.append(("table", rows))
    B.append(("p", "Qini coefficients computed on held-out cohorts with IPW weighting; higher means the ranking concentrates benefit among top-ranked customers."))
    B.append(("h1", "8. Optimisation results and policy comparison"))
    rows = [["Strategy", "Selected", "Spend", "Avoided events", "Net benefit (est.)"] + (["Net benefit (synthetic truth)"] if a.has_truth else [])]
    for s in run["strategies"]:
        rows.append([s["strategy"], f"{s['n_selected']:,.0f}", f(s["budget_used"], 0), f(s["expected_avoided_events"], 1), f(s["net_benefit"], 0)] +
                    ([f(s["synthetic_truth"]["net_benefit"], 0)] if a.has_truth and "synthetic_truth" in s else []))
    B.append(("table", rows))
    B.append(("p", f"Solver status: {summ['solver_status']}; binding constraints: {', '.join(summ['binding_constraints']) or 'none'}."))
    B.append(("h1", "9. Financial assumptions (analyst-specified)"))
    B.append(("bullets", [f"Value per avoided event: {f(cfg['value_per_event'], 0)}", f"Unit costs: {cfg['costs']}", f"Budget: {f(cfg['budget'], 0)}; agent slots: {cfg['agent_capacity']}; "
                          f"channel capacity: {cfg['channel_capacity']}", "Costs are subtracted exactly once in net benefit. These are assumptions, not measurements."]))
    B.append(("h1", "10. Scenario analysis (simulated)"))
    rows = [["Scenario", "Net benefit", "vs risk-first", "MC 5-95% (net)", "P(net>0)"]]
    for r in scenario_results:
        mc = r["monte_carlo"]
        rows.append([r["label"], f(r["optimised"]["net_benefit"], 0), f(r["net_benefit_advantage_over_risk_first"], 0),
                     f"{f(mc['net_benefit_p05_p95'][0], 0)} to {f(mc['net_benefit_p05_p95'][1], 0)}" if mc.get("draws") else "n/a", f(mc.get("prob_net_positive"), 2) if mc.get("draws") else "n/a"])
    B.append(("table", rows))
    B.append(("p", "Monte Carlo ranges reflect sampling uncertainty in effect estimates only (independent errors); they exclude confounding and model misspecification."))
    B.append(("h1", "11. Data limitations"))
    B.append(("bullets", ["Synthetic data embody the assumptions of the generator; recovery of known effects validates the code, not real-world performance.",
                          "Unmeasured confounding cannot be excluded in observational assignment.", "Delivery/receipt is imperfect: estimates are ITT effects of assignment.",
                          "Only a single decision period is modelled; repeated-contact fatigue and dynamics are not."]))
    B.append(("h1", "12. Recommendations"))
    B.append(("bullets", ["Use the estimates to prioritise candidates for a randomised holdout (Experiment Designer) before scaling any intervention.",
                          "Prefer the conservative policy when estimate precision is low or the estimator disagrees with placebo checks.",
                          "Re-run monitoring each cohort; investigate drift before trusting absolute risk levels."]))
    B.append(("h1", "13. Governance considerations"))
    B.append(("bullets", ["Protected/audit-only attributes are excluded from models and optimiser; fairness audit tables are descriptive.",
                          "Consequential or low-confidence recommendations are flagged for human review; overrides are logged with reason and reviewer.",
                          "Every recommendation stores model, policy and data versions for reproducible audit."]))
    return B


def to_markdown(B) -> str:
    out = []
    for kind, v in B:
        if kind == "title": out.append(f"# {v}\n")
        elif kind == "h1": out.append(f"\n## {v}\n")
        elif kind == "p": out.append(v + "\n")
        elif kind == "note": out.append(f"> {v}\n")
        elif kind == "bullets": out.append("\n".join(f"- {x}" for x in v) + "\n")
        elif kind == "table":
            out.append("| " + " | ".join(v[0]) + " |\n|" + "---|" * len(v[0]) + "\n" + "\n".join("| " + " | ".join(map(str, r)) + " |" for r in v[1:]) + "\n")
    return "\n".join(out)


def to_html(B) -> str:
    h = ["<html><head><meta charset='utf-8'><title>CAUSAL-X Report</title><style>body{font-family:Segoe UI,Arial;max-width:900px;margin:2rem auto;color:#0f172a}"
         "table{border-collapse:collapse;width:100%;font-size:13px}td,th{border:1px solid #cbd5e1;padding:4px 8px;text-align:left}th{background:#f1f5f9}"
         ".note{background:#fef9c3;padding:8px 12px;border-left:4px solid #ca8a04}</style></head><body>"]
    for kind, v in B:
        if kind == "title": h.append(f"<h1>{html.escape(v)}</h1>")
        elif kind == "h1": h.append(f"<h2>{html.escape(v)}</h2>")
        elif kind == "p": h.append(f"<p>{html.escape(v)}</p>")
        elif kind == "note": h.append(f"<p class='note'>{html.escape(v)}</p>")
        elif kind == "bullets": h.append("<ul>" + "".join(f"<li>{html.escape(x)}</li>" for x in v) + "</ul>")
        elif kind == "table":
            h.append("<table><tr>" + "".join(f"<th>{html.escape(c)}</th>" for c in v[0]) + "</tr>" +
                     "".join("<tr>" + "".join(f"<td>{html.escape(str(c))}</td>" for c in r) + "</tr>" for r in v[1:]) + "</table>")
    return "".join(h) + "</body></html>"


def to_pdf(B, path: Path):
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import ListFlowable, ListItem, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    st = getSampleStyleSheet()
    doc = SimpleDocTemplate(str(path), pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm, title="CAUSAL-X Executive Report")
    fl = []
    esc = lambda s: html.escape(str(s))
    for kind, v in B:
        if kind == "title": fl += [Paragraph(esc(v), st["Title"])]
        elif kind == "h1": fl += [Spacer(1, 6), Paragraph(esc(v), st["Heading2"])]
        elif kind == "p": fl += [Paragraph(esc(v), st["BodyText"]), Spacer(1, 4)]
        elif kind == "note": fl += [Paragraph(f"<i>{esc(v)}</i>", st["BodyText"]), Spacer(1, 4)]
        elif kind == "bullets": fl += [ListFlowable([ListItem(Paragraph(esc(x), st["BodyText"])) for x in v], bulletType="bullet", leftIndent=12), Spacer(1, 4)]
        elif kind == "table":
            cell = st["BodyText"].clone("c", fontSize=7.5, leading=9)
            data = [[Paragraph(esc(c), cell) for c in r] for r in v]
            t = Table(data, repeatRows=1)
            t.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")), ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#94a3b8")),
                                   ("VALIGN", (0, 0), (-1, -1), "TOP")]))
            fl += [t, Spacer(1, 6)]
    doc.build(fl)


def generate(a, run: dict, base_problem=None, base_cfg=None, mc_draws=100) -> dict:
    scen = []
    if base_problem is not None:
        for k, v in SCENARIO_CATALOGUE.items():
            scen.append(run_scenario(base_problem, base_cfg, v["overrides"], v["label"], 42, mc_draws))
    B = build_blocks(a, run, scen)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%d-%H%M%S")
    base = settings.artifacts_dir / "reports" / f"causalx_report_{a.dataset}_{stamp}"
    base.parent.mkdir(parents=True, exist_ok=True)
    md, hh = base.with_suffix(".md"), base.with_suffix(".html")
    md.write_text(to_markdown(B), encoding="utf-8"); hh.write_text(to_html(B), encoding="utf-8")
    pdf = None
    try:
        to_pdf(B, base.with_suffix(".pdf")); pdf = base.with_suffix(".pdf").name
    except Exception as e:  # PDF is best-effort
        pdf = None
    return {"markdown": md.name, "html": hh.name, "pdf": pdf, "scenarios_included": len(scen)}
